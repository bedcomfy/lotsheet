import { expect, test } from "@playwright/test";
import { FUSION_REQUEST_HEADER } from "../app/lib/fusion/config";

test("Northwest index, partial-name search, charge pagination, bus filter, cache and connection loss", async ({ context, page }, testInfo) => {
  const payload = Buffer.from(JSON.stringify({ exp: Math.floor(Date.now() / 1000) + 14400 })).toString("base64url");
  const saved = await context.request.post("/api/fusion/session", { headers: { Origin: "http://localhost:3002", [FUSION_REQUEST_HEADER]: "1" }, data: { accessToken: "e30." + payload + ".mock-token-1" } });
  expect(saved.status()).toBe(200);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const partsRequests: string[] = [];
  page.on("request", request => { if (request.url().includes("/api/fusion/parts")) partsRequests.push(request.url()); });
  await page.goto("/fusion/parts");
  await expect(page.getByText("Index complete", { exact: true })).toBeVisible();
  const search = page.getByRole("combobox", { name: "Part number or name" });
  await search.fill("cool bulk");
  await page.getByRole("option", { name: /910090/ }).click();
  await expect(page.getByText("All available entries loaded", { exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "3,060.47 Unit not supplied", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: /NWD-1676/ })).toBeVisible();
  await page.getByRole("button", { name: /All buses Bus/ }).click();
  await page.getByRole("option", { name: "Bus 6403", exact: true }).click();
  await expect(page.getByRole("cell", { name: /NWD-1676/ })).toHaveCount(0);
  await expect(page.getByText("Return", { exact: true })).toBeVisible();
  await page.getByText("Include part returns", { exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Include part returns" })).not.toBeChecked();
  await expect(page.getByText("Return", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("parts-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: testInfo.outputPath("parts-phone.png"), fullPage: true });
  expect(partsRequests.some(url => url.includes("kind=history") && url.includes("offset=2"))).toBe(true);
  partsRequests.length = 0;
  await page.reload();
  await expect(page.getByText("Index complete", { exact: true })).toBeVisible();
  expect(partsRequests.every(url => url.includes("kind=context"))).toBe(true);
  await search.fill("910103");
  await page.getByRole("option", { name: /910103/ }).click();
  await expect(page.getByText("No matching charge entries", { exact: true })).toBeVisible();
  await context.clearCookies();
  await page.getByRole("button", { name: "Refresh history" }).click();
  await expect(page.getByText("Connect to Oracle Fusion", { exact: true })).toBeVisible();
  await expect(page.getByRole("table")).toHaveCount(0);
  expect(errors).toEqual([]);
});

import { expect, test } from "@playwright/test";
import { FUSION_REQUEST_HEADER } from "../app/lib/fusion/config";

test("Northwest index, partial-name search, charge pagination, bus filter, cache and connection loss", async ({ context, page }, testInfo) => {
  const payload = Buffer.from(JSON.stringify({ exp: Math.floor(Date.now() / 1000) + 14400 })).toString("base64url");
  const saved = await context.request.post("/api/fusion/session", { headers: { Origin: "http://localhost:3002", [FUSION_REQUEST_HEADER]: "1" }, data: { accessToken: "e30." + payload + ".mock-token-1" } });
  expect(saved.status()).toBe(200);
  const contributedCookie = (await context.cookies()).find(cookie => cookie.name === "__Secure-pace-fusion-tester")!;
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const partsRequests: string[] = [];
  page.on("request", request => { if (request.url().includes("/api/fusion/parts")) partsRequests.push(request.url()); });
  await page.goto("/fusion/parts");
  await expect(page.getByText("Index complete", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Update saved catalog", exact: true }).click();
  await expect(page.getByText("2 saved parts", { exact: true })).toBeVisible();
  await expect(page.getByRole("timer", { name: "Oracle access time remaining" })).toContainText(/\d{2}:\d{2}:\d{2} remaining/);
  const search = page.getByRole("combobox", { name: "Part number or name" });
  await search.fill("cool bulk");
  await page.getByRole("option", { name: /910090/ }).click();
  await expect(page.getByText("All available entries loaded", { exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "3,060.47 Unit not supplied", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: /NWD-1676/ })).toBeVisible();
  const busFilter = page.getByRole("textbox", { name: "Bus number", exact: true });
  await busFilter.fill("9999");
  await expect(page.getByText("No matching charge entries for bus 9999", { exact: true })).toBeVisible();
  await busFilter.fill("6403");
  await expect(page.getByRole("cell", { name: /NWD-1676/ })).toHaveCount(0);
  const history = page.getByRole("region", { name: "Part charge history", exact: true });
  await expect(history).toContainText("Selvin A Zambrano");
  await expect(history).toContainText("Peter M Katona");
  await expect(history).toContainText("Synthetic technician");
  await expect(page.getByText("Return", { exact: true })).toBeVisible();
  await page.getByText("Include part returns", { exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Include part returns" })).not.toBeChecked();
  await expect(page.getByText("Return", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("parts-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  expect(await page.getByRole("textbox", { name: "Search saved parts" }).evaluate(el => el.getBoundingClientRect().right <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("parts-phone.png"), fullPage: true });
  expect(partsRequests.some(url => url.includes("kind=history") && url.includes("offset=2"))).toBe(true);
  partsRequests.length = 0;
  await page.reload();
  await expect(page.getByText("Index complete", { exact: true })).toBeVisible();
  expect(partsRequests.every(url => url.includes("kind=context"))).toBe(true);
  await search.fill("910103");
  await page.getByRole("option", { name: /910103/ }).click();
  await expect(page.getByText("No matching charge entries", { exact: true })).toBeVisible();
  await context.clearCookies();
  const sharedRead = page.waitForResponse(response => response.url().includes("kind=history"));
  await page.getByRole("button", { name: "Refresh history" }).click();
  expect((await sharedRead).status()).toBe(200);
  await expect(page.getByText("No matching charge entries", { exact: true })).toBeVisible();
  // Cookie loss no longer disconnects a test device. Remove the actual saved
  // connection using its contributor's permit to exercise connection loss.
  const removed = await context.request.delete("/api/fusion/session", { headers: { Origin: "http://localhost:3002", [FUSION_REQUEST_HEADER]: "1", Cookie: contributedCookie.name + "=" + contributedCookie.value } });
  expect(removed.status()).toBe(200);
  await page.getByRole("button", { name: "Refresh history" }).click();
  await expect(page.getByText("Connect to Oracle for live stock and charges", { exact: true })).toBeVisible();
  await expect(page.getByRole("table", { name: "Northwest part charge history" })).toHaveCount(0);
  // Other connection tests can leave another shared test credential. Model all
  // Oracle access being unavailable without changing the catalog's real handler.
  await page.route("**/api/fusion/parts?kind=context", route => route.fulfill({ status: 401, contentType: "application/json", body: JSON.stringify({ code: "AUTH" }) }));
  await page.reload();
  await expect(page.getByText("2 saved parts", { exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Search saved parts" }).fill("COOLANT-MPN");
  await expect(page.getByRole("region", { name: "Saved Northwest parts", exact: true })).toContainText("910090");
  await expect(page.getByRole("button", { name: "Update saved catalog", exact: true })).toBeDisabled();
  expect(errors).toEqual([]);
});
